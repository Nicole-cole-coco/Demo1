type NodeTuple = readonly [
  beat: string,
  story: string,
  line: string,
  subject: string,
  resolution: string
];

function journeyNodes(items: readonly NodeTuple[]): readonly NodeSeed[] {
  if (items.length !== 20) {
    throw new Error(`Base relationship scenarios require 20 nodes; received ${items.length}.`);
  }

  return items.map(([beat, story, line, subject, resolution]) => ({
    beat,
    story,
    line,
    subject,
    resolution,
    prompt: `关系走到“${beat}”这一刻，你准备怎样回应？`
  }));
}

